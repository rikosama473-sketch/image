#!/usr/bin/env python3
"""Generate images from a local/Hugging Face Diffusers model with an optional style LoRA.

The engine defaults to local-only model loading. Pass --allow-download explicitly
to permit downloading weights from a model hub. It never uploads the prompt or
images generated by this script to an inference service.
"""
from __future__ import annotations

import argparse
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True, help="Local Diffusers model directory or cached hub identifier")
    parser.add_argument("--lora", help="Optional local LoRA file/directory or cached hub identifier")
    parser.add_argument("--lora-weight-name", help="Optional filename within a LoRA directory/repository")
    parser.add_argument("--lora-scale", type=float, default=0.8, help="Style LoRA strength, usually tested around 0.5–1.0")
    parser.add_argument("--prompt", required=True, help="Positive text prompt")
    parser.add_argument("--negative-prompt", default="", help="Negative text prompt")
    parser.add_argument("--width", type=int, default=512)
    parser.add_argument("--height", type=int, default=512)
    parser.add_argument("--steps", type=int, default=20)
    parser.add_argument("--guidance-scale", type=float, default=7.0)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--count", type=int, default=1, help="Generate sequentially to keep peak memory lower")
    parser.add_argument("--device", choices=("auto", "cpu", "cuda", "mps"), default="auto")
    parser.add_argument("--precision", choices=("auto", "fp16", "bf16", "fp32"), default="auto")
    parser.add_argument("--low-memory", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--cpu-offload", action="store_true", help="Offload model components to system RAM; requires CUDA and accelerate")
    parser.add_argument("--allow-download", action="store_true", help="Allow downloading the model/LoRA from its hub; off by default")
    parser.add_argument("--output-dir", type=Path, default=Path("outputs/generated"))
    return parser


def validate_args(args: argparse.Namespace, parser: argparse.ArgumentParser) -> None:
    if args.count < 1 or args.count > 16:
        parser.error("--count must be between 1 and 16; generations are run sequentially.")
    if args.steps < 1 or args.steps > 150:
        parser.error("--steps must be between 1 and 150.")
    if args.width < 64 or args.height < 64 or args.width % 8 or args.height % 8:
        parser.error("--width and --height must be at least 64 and multiples of 8.")
    if not 0 <= args.lora_scale <= 2:
        parser.error("--lora-scale must be between 0 and 2.")
    if args.guidance_scale < 0:
        parser.error("--guidance-scale cannot be negative.")
    if args.cpu_offload and args.device == "cpu":
        parser.error("--cpu-offload requires CUDA; it cannot be combined with --device cpu.")
    if args.cpu_offload and args.device == "mps":
        parser.error("--cpu-offload is supported only for CUDA in this script.")


def choose_device(torch: Any, requested: str) -> str:
    if requested != "auto":
        if requested == "cuda" and not torch.cuda.is_available():
            raise RuntimeError("CUDA was requested but PyTorch cannot access a CUDA GPU.")
        if requested == "mps" and not (hasattr(torch.backends, "mps") and torch.backends.mps.is_available()):
            raise RuntimeError("MPS was requested but is not available in this PyTorch installation.")
        if requested == "cpu":
            return "cpu"
        return requested
    if torch.cuda.is_available():
        return "cuda"
    if hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
        return "mps"
    return "cpu"


def choose_dtype(torch: Any, precision: str, device: str) -> Any:
    if precision == "fp32":
        return torch.float32
    if precision == "fp16":
        return torch.float16
    if precision == "bf16":
        return torch.bfloat16
    if device == "cuda":
        return torch.float16
    # Conservative default for CPU/MPS; users can explicitly test another dtype.
    return torch.float32


def resolve_lora_source(source: str, weight_name: str | None) -> tuple[str, str | None]:
    candidate = Path(source).expanduser()
    if candidate.is_file():
        return str(candidate.parent.resolve()), weight_name or candidate.name
    return source, weight_name


def run_generation_batch(
    args: argparse.Namespace,
    pipe: Any,
    torch: Any,
    device: str,
    run_dir: Path,
    diffusers_version: str = "unknown",
    torch_version: str = "unknown",
) -> dict[str, Any]:
    """Run requests sequentially and preserve an auditable result manifest."""
    run_dir.mkdir(parents=True, exist_ok=False)
    saved: list[dict[str, Any]] = []
    failures: list[dict[str, Any]] = []
    for index in range(args.count):
        image_seed = args.seed + index
        try:
            generator_device = "cuda" if device == "cuda" else "cpu"
            generator = torch.Generator(device=generator_device).manual_seed(image_seed)
            call_args: dict[str, Any] = {
                "prompt": args.prompt, "negative_prompt": args.negative_prompt or None,
                "width": args.width, "height": args.height,
                "num_inference_steps": args.steps, "guidance_scale": args.guidance_scale,
                "generator": generator,
            }
            if args.lora:
                call_args["cross_attention_kwargs"] = {"scale": args.lora_scale}
            result = pipe(**call_args)
            if not getattr(result, "images", None):
                raise RuntimeError("El pipeline no devolvió ninguna imagen.")
            image = result.images[0]
            stem = f"image-{index + 1:03d}-seed-{image_seed}"
            image_path = run_dir / f"{stem}.png"
            image.save(image_path)
            # Count the image once it exists on disk. A sidecar failure must not
            # make the UI hide a valid PNG; the batch itself can still be partial.
            saved.append({"seed": image_seed, "image_path": image_path.name})
            metadata = {
                "model": args.model, "lora": args.lora,
                "lora_weight_name": args.lora_weight_name,
                "lora_scale": args.lora_scale if args.lora else None,
                "prompt": args.prompt, "negative_prompt": args.negative_prompt,
                "seed": image_seed, "width": args.width, "height": args.height,
                "steps": args.steps, "guidance_scale": args.guidance_scale,
                "scheduler": type(pipe.scheduler).__name__ if getattr(pipe, "scheduler", None) else None,
                "device": device, "precision": args.precision,
                "diffusers_version": diffusers_version, "torch_version": torch_version,
                "python_version": platform.python_version(), "safetensors_only": True,
                "allow_download": args.allow_download, "image_path": image_path.name,
            }
            (run_dir / f"{stem}.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            print(f"Saved {image_path}")
        except Exception as exc:
            failure = {"seed": image_seed, "error": f"{type(exc).__name__}: {exc}"}
            failures.append(failure)
            print(f"Generation failed for seed {image_seed}: {failure['error']}", file=sys.stderr)

    if len(saved) == args.count and not failures:
        status, exit_code = "completed", 0
    elif saved:
        status, exit_code = "partial", 3
    else:
        status, exit_code = "failed", 1
    manifest = {
        "schema_version": 1, "run_status": status,
        "requested_count": args.count, "generated_count": len(saved), "failed_count": len(failures),
        "requested_seed": args.seed, "generated": saved, "failures": failures,
        "parameters": {
            "model": args.model, "lora": args.lora or None,
            "lora_weight_name": args.lora_weight_name or None,
            "lora_scale": args.lora_scale if args.lora else None,
            "prompt": args.prompt, "negative_prompt": args.negative_prompt,
            "width": args.width, "height": args.height, "steps": args.steps,
            "guidance_scale": args.guidance_scale, "device": device,
            "precision": args.precision, "low_memory": args.low_memory,
            "cpu_offload": args.cpu_offload, "allow_download": args.allow_download,
        },
        "runtime": {
            "python_version": platform.python_version(), "torch_version": torch_version,
            "diffusers_version": diffusers_version,
        },
    }
    try:
        (run_dir / "run-manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    except OSError as exc:
        print(f"Could not write run manifest: {type(exc).__name__}: {exc}", file=sys.stderr)
        if status == "completed":
            exit_code = 3
            manifest["run_status"] = "partial"
            manifest["manifest_write_error"] = f"{type(exc).__name__}: {exc}"
    print(f"Run status: {manifest['run_status']} ({len(saved)}/{args.count} images)")
    return {"exit_code": exit_code, "manifest": manifest, "run_dir": str(run_dir)}


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    validate_args(args, parser)

    try:
        import torch
        import diffusers
        from diffusers import AutoPipelineForText2Image
    except ImportError as exc:
        print(
            "Faltan dependencias del motor de difusión. Instala PyTorch para tu equipo y "
            "luego ejecuta: python -m pip install -r requirements-diffusion.txt",
            file=sys.stderr,
        )
        raise SystemExit(2) from exc

    try:
        device = choose_device(torch, args.device)
        dtype = choose_dtype(torch, args.precision, device)
        if args.cpu_offload and device != "cuda":
            raise RuntimeError("--cpu-offload requires a CUDA GPU; choose --device cuda or use --device auto on a CUDA machine.")
    except RuntimeError as exc:
        parser.error(str(exc))

    model_path = Path(args.model).expanduser()
    if model_path.exists() and not model_path.is_dir():
        parser.error("--model must be a Diffusers model directory or hub identifier, not a single checkpoint file.")
    if not args.allow_download and not model_path.is_dir():
        # A hub identifier can still work when its files are already cached.
        local_files_only = True
    else:
        local_files_only = not args.allow_download

    try:
        pipe = AutoPipelineForText2Image.from_pretrained(
            args.model,
            torch_dtype=dtype,
            use_safetensors=True,
            local_files_only=local_files_only,
        )
        if args.lora:
            lora_source, weight_name = resolve_lora_source(args.lora, args.lora_weight_name)
            pipe.load_lora_weights(
                lora_source,
                weight_name=weight_name,
                adapter_name="image_style",
                local_files_only=local_files_only,
            )
        if args.low_memory:
            if hasattr(pipe, "enable_attention_slicing"):
                pipe.enable_attention_slicing("max")
            if hasattr(pipe, "enable_vae_slicing"):
                pipe.enable_vae_slicing()
        if args.cpu_offload:
            pipe.enable_model_cpu_offload()
        else:
            pipe.to(device)
    except Exception as exc:
        print(f"Could not load the selected model/LoRA: {type(exc).__name__}: {exc}", file=sys.stderr)
        print(
            "Check that the model directory/identifier is a Diffusers-compatible model, "
            "the LoRA matches its base family, and remote downloads were explicitly enabled if needed.",
            file=sys.stderr,
        )
        return 2

    output_root = args.output_dir.expanduser()
    if not output_root.is_absolute():
        output_root = Path.cwd() / output_root
    run_stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    run_dir = output_root / f"run-{run_stamp}-seed-{args.seed}"
    batch_result = run_generation_batch(
        args, pipe, torch, device, run_dir,
        diffusers_version=getattr(diffusers, "__version__", "unknown"),
        torch_version=getattr(torch, "__version__", "unknown"),
    )
    print(f"Run directory: {run_dir}")
    print("CPU generation can be very slow. Memory and output quality depend on the selected base model and hardware.")
    return int(batch_result["exit_code"])


if __name__ == "__main__":
    raise SystemExit(main())
