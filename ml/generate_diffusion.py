#!/usr/bin/env python3
"""Generate images from a local/Hugging Face Diffusers model with an optional style LoRA.

The engine defaults to local-only model loading. Pass --allow-download explicitly
to permit downloading weights from a model hub. It never uploads the prompt or
images generated by this script to an inference service.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from generation_presets import CHARACTER_PROMPT_SUFFIX, WHITE_BACKGROUND_PROMPT_SUFFIX, build_generation_prompts


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True, help="Local Diffusers model directory or cached hub identifier")
    parser.add_argument("--revision", default="main", help="Model hub branch/commit to load (ignored for local model directories)")
    parser.add_argument("--variant", choices=("fp16", "none"), default="fp16", help="Select fp16 safetensors weights on the model revision, or none for standard weights")
    parser.add_argument("--lora", help="Optional local LoRA file/directory or cached hub identifier")
    parser.add_argument("--lora-weight-name", help="Optional filename within a LoRA directory/repository")
    parser.add_argument("--lora-scale", type=float, default=0.8, help="Style LoRA strength, usually tested around 0.5–1.0")
    parser.add_argument("--prompt", required=True, help="Effective positive prompt sent to the model")
    parser.add_argument("--user-prompt", default="", help="Original user prompt, retained separately in the manifest")
    parser.add_argument("--negative-prompt", default="", help="Effective negative prompt sent to the model")
    parser.add_argument("--user-negative-prompt", default="", help="Additional user negative terms, excluding built-in presets")
    parser.add_argument("--character-mode", action="store_true", help="Use one-character composition mode")
    parser.add_argument("--transparent-background", action="store_true", help="Run local isnet-anime segmentation and save verified RGBA transparency")
    parser.add_argument("--cpu-threads", type=int, default=4, help="Maximum CPU intra-op threads (1-6)")
    parser.add_argument("--width", type=int, default=512)
    parser.add_argument("--height", type=int, default=512)
    parser.add_argument("--steps", type=int, default=20)
    parser.add_argument("--guidance-scale", type=float, default=7.0)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--count", type=int, default=1, help="Generate sequentially to keep peak memory lower")
    parser.add_argument("--device", choices=("auto", "cpu", "cuda", "mps"), default="auto")
    parser.add_argument("--precision", choices=("auto", "fp16", "bf16", "fp32"), default="auto")
    parser.add_argument("--low-memory", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--cpu-offload", action="store_true", help="Offload model components to system RAM; requires CUDA and accelerate")
    parser.add_argument("--allow-download", action="store_true", help="Allow downloading the model/LoRA from its hub; off by default")
    parser.add_argument("--output-dir", type=Path, default=Path("outputs/generated"))
    return parser


def validate_args(args: argparse.Namespace, parser: argparse.ArgumentParser) -> None:
    if args.count < 1 or args.count > 2:
        parser.error("--count must be between 1 and 2; images are processed sequentially to protect memory.")
    if args.steps < 1 or args.steps > 30:
        parser.error("--steps must be between 1 and 30 for the safe local profile.")
    if args.width < 64 or args.height < 64 or args.width > 768 or args.height > 1024 or args.width % 8 or args.height % 8:
        parser.error("--width must be 64–768, --height 64–1024, and both multiples of 8.")
    if args.width * args.height > 786432:
        parser.error("Image area may not exceed 786432 pixels in the safe local profile.")
    if args.cpu_threads < 1 or args.cpu_threads > 6:
        parser.error("--cpu-threads must be between 1 and 6.")
    if not 0 <= args.lora_scale <= 2:
        parser.error("--lora-scale must be between 0 and 2.")
    if not 0 <= args.guidance_scale <= 12:
        parser.error("--guidance-scale must be between 0 and 12 in the safe local profile.")
    if args.cpu_offload and args.device == "cpu":
        parser.error("--cpu-offload requires CUDA; it cannot be combined with --device cpu.")
    if args.cpu_offload and args.device == "mps":
        parser.error("--cpu-offload is supported only for CUDA in this script.")


def choose_device(torch: Any, requested: str) -> str:
    if requested != "auto":
        if requested == "cuda" and not torch.cuda.is_available():
            raise RuntimeError("CUDA was requested but PyTorch cannot access a CUDA GPU.")
        if requested == "mps" and not (hasattr(torch.backends, "mps") and torch.backends.mps.is_available()):
            raise RuntimeError("MPS was requested but is not available in this PyTorch installation.")
        if requested == "cpu":
            return "cpu"
        return requested
    if torch.cuda.is_available():
        return "cuda"
    if hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
        return "mps"
    return "cpu"


def choose_dtype(torch: Any, precision: str, device: str) -> Any:
    if precision == "fp32":
        return torch.float32
    if precision == "fp16":
        return torch.float16
    if precision == "bf16":
        return torch.bfloat16
    if device == "cuda":
        return torch.float16
    # Conservative default for CPU/MPS; users can explicitly test another dtype.
    return torch.float32


def resolve_lora_source(source: str, weight_name: str | None) -> tuple[str, str | None]:
    candidate = Path(source).expanduser()
    if candidate.is_file():
        return str(candidate.parent.resolve()), weight_name or candidate.name
    return source, weight_name



def _encode_prompt(tokenizer: Any, text: str) -> list[int]:
    return list(tokenizer.encode(text, add_special_tokens=False))


def _decode_prompt(tokenizer: Any, token_ids: list[int]) -> str:
    try:
        return str(tokenizer.decode(token_ids, skip_special_tokens=True)).strip()
    except TypeError:
        return str(tokenizer.decode(token_ids)).strip()


def _token_count(tokenizer: Any, text: str) -> int:
    return len(_encode_prompt(tokenizer, text))


def _fit_positive_prompt(
    user_prompt: str,
    character_mode: bool,
    transparent_background: bool,
    tokenizer: Any,
    max_tokens: int,
) -> tuple[str, bool]:
    """Keep user details first but reserve tokens for the fixed character/cutout recipe."""
    positive, _ = build_generation_prompts(
        user_prompt, "", character_mode, transparent_background
    )
    if _token_count(tokenizer, positive) <= max_tokens:
        return positive, False

    suffix_parts = []
    if character_mode:
        suffix_parts.append(CHARACTER_PROMPT_SUFFIX)
    if transparent_background:
        suffix_parts.append(WHITE_BACKGROUND_PROMPT_SUFFIX)
    suffix = ", ".join(suffix_parts)
    suffix_tokens = _encode_prompt(tokenizer, suffix) if suffix else []
    source_tokens = _encode_prompt(tokenizer, user_prompt)
    user_budget = max(0, max_tokens - len(suffix_tokens) - (1 if suffix else 0))
    kept_user_tokens = source_tokens[:user_budget]
    user_text = _decode_prompt(tokenizer, kept_user_tokens)
    parts = [part for part in (user_text, suffix) if part]
    candidate = ", ".join(parts)

    while _token_count(tokenizer, candidate) > max_tokens and kept_user_tokens:
        kept_user_tokens.pop()
        user_text = _decode_prompt(tokenizer, kept_user_tokens)
        candidate = ", ".join(part for part in (user_text, suffix) if part)
    if _token_count(tokenizer, candidate) > max_tokens:
        candidate = _decode_prompt(tokenizer, _encode_prompt(tokenizer, candidate)[:max_tokens])
    return candidate, True


def _fit_negative_prompt(
    negative_prompt: str,
    tokenizer: Any,
    max_tokens: int,
) -> tuple[str, bool]:
    """Keep early, built-in protection tags before optional user extras when truncating."""
    if _token_count(tokenizer, negative_prompt) <= max_tokens:
        return negative_prompt, False
    accepted: list[str] = []
    for term in (item.strip() for item in negative_prompt.split(",")):
        if not term:
            continue
        candidate = ", ".join([*accepted, term])
        if _token_count(tokenizer, candidate) <= max_tokens:
            accepted.append(term)
    result = ", ".join(accepted)
    if not result:
        result = _decode_prompt(tokenizer, _encode_prompt(tokenizer, negative_prompt)[:max_tokens])
    return result, True


def prepare_generation_prompts(
    args: argparse.Namespace,
    tokenizer: Any,
    max_tokens: int | None = None,
) -> tuple[str, str, bool, bool]:
    """Rebuild from the user's original text and keep both prompts inside the CLIP window."""
    if args.user_prompt:
        user_prompt = args.user_prompt
        # When invoked by the local server the submitted negative is already composed;
        # the separate user field is the unmodified optional extra.
        user_negative = args.user_negative_prompt
    else:
        user_prompt = args.prompt
        user_negative = args.user_negative_prompt or args.negative_prompt

    _, raw_negative = build_generation_prompts(
        user_prompt,
        user_negative,
        bool(args.character_mode),
        bool(args.transparent_background),
    )
    _, reported_limit = (None, getattr(tokenizer, "model_max_length", 77))
    try:
        reported_limit = int(reported_limit)
    except (TypeError, ValueError, OverflowError):
        reported_limit = 77
    if reported_limit > 512:
        reported_limit = 77
    token_limit = max_tokens if max_tokens is not None else min(75, max(1, reported_limit - 2))
    effective_prompt, prompt_truncated = _fit_positive_prompt(
        user_prompt,
        bool(args.character_mode),
        bool(args.transparent_background),
        tokenizer,
        token_limit,
    )
    effective_negative, negative_truncated = _fit_negative_prompt(
        raw_negative, tokenizer, token_limit
    )
    return effective_prompt, effective_negative, prompt_truncated, negative_truncated


def run_generation_batch(
    args: argparse.Namespace,
    pipe: Any,
    torch: Any,
    device: str,
    run_dir: Path,
    diffusers_version: str = "unknown",
    torch_version: str = "unknown",
    cutout_session: Any = None,
) -> dict[str, Any]:
    """Run requests sequentially and preserve an auditable result manifest."""
    run_dir.mkdir(parents=True, exist_ok=False)
    saved: list[dict[str, Any]] = []
    failures: list[dict[str, Any]] = []
    tokenizer = getattr(pipe, "tokenizer", None)
    if tokenizer is not None and callable(getattr(tokenizer, "encode", None)):
        effective_prompt, effective_negative_prompt, prompt_truncated, negative_prompt_truncated = prepare_generation_prompts(args, tokenizer)
    else:
        # Lightweight fake pipelines used by unit tests may not expose a tokenizer.
        effective_prompt, effective_negative_prompt = args.prompt, args.negative_prompt
        prompt_truncated = negative_prompt_truncated = False
    if prompt_truncated or negative_prompt_truncated:
        print("Aviso: se ajustó el prompt al límite del tokenizador; el texto original se conserva en los metadatos.", file=sys.stderr)
    for index in range(args.count):
        image_seed = args.seed + index
        try:
            generator_device = "cuda" if device == "cuda" else "cpu"
            generator = torch.Generator(device=generator_device).manual_seed(image_seed)
            call_args: dict[str, Any] = {
                "prompt": effective_prompt, "negative_prompt": effective_negative_prompt or None,
                "width": args.width, "height": args.height,
                "num_inference_steps": args.steps, "guidance_scale": args.guidance_scale,
                "generator": generator,
            }
            if args.lora:
                call_args["cross_attention_kwargs"] = {"scale": args.lora_scale}
            result = pipe(**call_args)
            if not getattr(result, "images", None):
                raise RuntimeError("El pipeline no devolvió ninguna imagen.")
            image = result.images[0]
            if args.transparent_background:
                if cutout_session is None:
                    raise RuntimeError("El recortador anime local no está preparado; no se guardó una imagen sin transparencia verificada.")
                from rembg import remove
                cutout = remove(
                    image,
                    session=cutout_session,
                    alpha_matting=False,
                    post_process_mask=False,
                    decontaminate=True,
                )
                if not hasattr(cutout, "getchannel") or not hasattr(cutout, "convert"):
                    raise RuntimeError("El recortador local no devolvió una imagen con canal alfa verificable.")
                cutout = cutout.convert("RGBA")
                alpha_histogram = cutout.getchannel("A").histogram()
                if sum(alpha_histogram[:255]) <= 0:
                    raise RuntimeError("El recortador no encontró transparencia; no se guardó un falso PNG transparente.")
                image = cutout
            stem = f"image-{index + 1:03d}-seed-{image_seed}"
            image_path = run_dir / f"{stem}.png"
            image.save(image_path)
            # Count the image once it exists on disk. A sidecar failure must not
            # make the UI hide a valid PNG; the batch itself can still be partial.
            saved.append({"seed": image_seed, "image_path": image_path.name})
            metadata = {
                "model": args.model, "model_revision": args.revision, "model_variant": args.variant, "lora": args.lora,
                "lora_weight_name": args.lora_weight_name,
                "lora_scale": args.lora_scale if args.lora else None,
                "prompt": args.user_prompt or args.prompt,
                "effective_prompt": effective_prompt,
                "negative_prompt": effective_negative_prompt,
                "prompt_truncated": prompt_truncated,
                "negative_prompt_truncated": negative_prompt_truncated,
                "user_negative_prompt": args.user_negative_prompt,
                "character_mode": args.character_mode,
                "transparent_background": args.transparent_background,
                "transparent_engine": "rembg:isnet-anime" if args.transparent_background else None,
                "cpu_threads": args.cpu_threads,
                "seed": image_seed, "width": args.width, "height": args.height,
                "steps": args.steps, "guidance_scale": args.guidance_scale,
                "scheduler": type(pipe.scheduler).__name__ if getattr(pipe, "scheduler", None) else None,
                "device": device, "precision": args.precision,
                "diffusers_version": diffusers_version, "torch_version": torch_version,
                "python_version": platform.python_version(), "safetensors_only": True,
                "allow_download": args.allow_download, "image_path": image_path.name,
            }
            (run_dir / f"{stem}.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            print(f"Saved {image_path}")
        except Exception as exc:
            failure = {"seed": image_seed, "error": f"{type(exc).__name__}: {exc}"}
            failures.append(failure)
            print(f"Generation failed for seed {image_seed}: {failure['error']}", file=sys.stderr)

    if len(saved) == args.count and not failures:
        status, exit_code = "completed", 0
    elif saved:
        status, exit_code = "partial", 3
    else:
        status, exit_code = "failed", 1
    manifest = {
        "schema_version": 1, "run_status": status,
        "requested_count": args.count, "generated_count": len(saved), "failed_count": len(failures),
        "requested_seed": args.seed, "generated": saved, "failures": failures,
        "parameters": {
            "model": args.model, "model_revision": args.revision, "model_variant": args.variant, "lora": args.lora or None,
            "lora_weight_name": args.lora_weight_name or None,
            "lora_scale": args.lora_scale if args.lora else None,
            "prompt": args.user_prompt or args.prompt,
            "effective_prompt": effective_prompt, "negative_prompt": effective_negative_prompt,
            "prompt_truncated": prompt_truncated, "negative_prompt_truncated": negative_prompt_truncated,
            "user_negative_prompt": args.user_negative_prompt,
            "character_mode": args.character_mode,
            "transparent_background": args.transparent_background,
            "transparent_engine": "rembg:isnet-anime" if args.transparent_background else None,
            "cpu_threads": args.cpu_threads,
            "width": args.width, "height": args.height, "steps": args.steps,
            "guidance_scale": args.guidance_scale, "device": device,
            "precision": args.precision, "low_memory": args.low_memory,
            "cpu_offload": args.cpu_offload, "allow_download": args.allow_download,
        },
        "runtime": {
            "python_version": platform.python_version(), "torch_version": torch_version,
            "diffusers_version": diffusers_version,
        },
    }
    try:
        (run_dir / "run-manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    except OSError as exc:
        print(f"Could not write run manifest: {type(exc).__name__}: {exc}", file=sys.stderr)
        if status == "completed":
            exit_code = 3
            manifest["run_status"] = "partial"
            manifest["manifest_write_error"] = f"{type(exc).__name__}: {exc}"
    print(f"Run status: {manifest['run_status']} ({len(saved)}/{args.count} images)")
    return {"exit_code": exit_code, "manifest": manifest, "run_dir": str(run_dir)}



def build_model_load_options(
    args: argparse.Namespace,
    model_path: Path,
    dtype: Any,
    local_files_only: bool,
) -> dict[str, Any]:
    """Build safe Diffusers load options; prefer named safetensors variants over pickle."""
    options: dict[str, Any] = {
        "torch_dtype": dtype,
        "use_safetensors": True,
        "local_files_only": local_files_only,
    }
    if not model_path.is_dir():
        if not args.revision or len(args.revision) > 128:
            raise RuntimeError("The model revision must be a non-empty branch/commit name up to 128 characters.")
        options["revision"] = args.revision
        # In current Diffusers, variant selects model.fp16.safetensors from the
        # main revision; it is not the same as switching to an fp16 branch.
        if args.variant != "none":
            options["variant"] = args.variant
    return options


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    validate_args(args, parser)

    try:
        import torch
        import diffusers
        from diffusers import AutoPipelineForText2Image
    except ImportError as exc:
        print(
            "Faltan dependencias del motor de difusión. Instala PyTorch para tu equipo y "
            "luego ejecuta: python -m pip install -r requirements-diffusion.txt",
            file=sys.stderr,
        )
        raise SystemExit(2) from exc

    try:
        torch.set_num_threads(args.cpu_threads)
        try:
            torch.set_num_interop_threads(1)
        except RuntimeError:
            pass
        device = choose_device(torch, args.device)
        dtype = choose_dtype(torch, args.precision, device)
        if args.cpu_offload and device != "cuda":
            raise RuntimeError("--cpu-offload requires a CUDA GPU; choose --device cuda or use --device auto on a CUDA machine.")
    except RuntimeError as exc:
        parser.error(str(exc))

    model_path = Path(args.model).expanduser()
    if model_path.exists() and not model_path.is_dir():
        parser.error("--model must be a Diffusers model directory or hub identifier, not a single checkpoint file.")
    if not args.allow_download and not model_path.is_dir():
        # A hub identifier can still work when its files are already cached.
        local_files_only = True
    else:
        local_files_only = not args.allow_download

    cutout_session = None
    if args.transparent_background:
        cache_root = Path(os.environ.get("U2NET_HOME", str(Path.home() / ".u2net"))).expanduser()
        cutout_model_path = cache_root / "isnet-anime.onnx"
        if not args.allow_download and not cutout_model_path.is_file():
            print(
                f"Falta el modelo local de recorte {cutout_model_path}. "
                "Activá la descarga inicial de modelos o instalá el peso isnet-anime.onnx en esa caché. "
                "No se descargó nada porque la opción está desactivada.",
                file=sys.stderr,
            )
            return 2
        try:
            import onnxruntime as ort
            from rembg import new_session
            session_options = ort.SessionOptions()
            session_options.intra_op_num_threads = args.cpu_threads
            session_options.inter_op_num_threads = 1
            cutout_session = new_session("isnet-anime", sess_opts=session_options)
        except ImportError:
            print("Falta el recortador local. Ejecutá: python -m pip install -r requirements-avatar-cutout.txt. El modelo de recorte también se descarga una vez al primer uso.", file=sys.stderr)
            return 2
        except Exception as exc:
            print(f"No se pudo preparar isnet-anime: {type(exc).__name__}: {exc}", file=sys.stderr)
            print("Revisá la conexión inicial y el espacio en disco; no se enviaron imágenes a un servicio de inferencia remoto.", file=sys.stderr)
            return 2

    try:
        load_options = build_model_load_options(args, model_path, dtype, local_files_only)
        pipe = AutoPipelineForText2Image.from_pretrained(args.model, **load_options)
        if args.lora:
            lora_source, weight_name = resolve_lora_source(args.lora, args.lora_weight_name)
            pipe.load_lora_weights(
                lora_source,
                weight_name=weight_name,
                adapter_name="image_style",
                local_files_only=local_files_only,
            )
        if args.low_memory:
            if hasattr(pipe, "enable_attention_slicing"):
                pipe.enable_attention_slicing("max")
            if hasattr(pipe, "enable_vae_slicing"):
                pipe.enable_vae_slicing()
        if args.cpu_offload:
            pipe.enable_model_cpu_offload()
        else:
            pipe.to(device)
    except Exception as exc:
        print(f"Could not load the selected model/LoRA: {type(exc).__name__}: {exc}", file=sys.stderr)
        print(
            "Check that the model directory/identifier is a Diffusers-compatible model, "
            "the LoRA matches its base family, and remote downloads were explicitly enabled if needed.",
            file=sys.stderr,
        )
        return 2

    output_root = args.output_dir.expanduser()
    if not output_root.is_absolute():
        output_root = Path.cwd() / output_root
    run_stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    run_dir = output_root / f"run-{run_stamp}-seed-{args.seed}"
    batch_result = run_generation_batch(
        args, pipe, torch, device, run_dir,
        diffusers_version=getattr(diffusers, "__version__", "unknown"),
        torch_version=getattr(torch, "__version__", "unknown"),
        cutout_session=cutout_session,
    )
    print(f"Run directory: {run_dir}")
    print("CPU generation can be very slow. Memory and output quality depend on the selected base model and hardware.")
    return int(batch_result["exit_code"])


if __name__ == "__main__":
    raise SystemExit(main())
